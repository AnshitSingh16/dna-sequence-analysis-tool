from io import BytesIO
from datetime import datetime
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import (
    getSampleStyleSheet,
    ParagraphStyle
)
from reportlab.lib.units import mm
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    HRFlowable
)


# --------------------------------------------------
# COLOUR PALETTE
# --------------------------------------------------

NAVY = colors.HexColor("#17365D")
BLUE = colors.HexColor("#2878B5")
LIGHT_BLUE = colors.HexColor("#EAF2F8")
LIGHT_GREY = colors.HexColor("#F4F6F8")
DARK_GREY = colors.HexColor("#34495E")
MID_GREY = colors.HexColor("#7B8794")
WHITE = colors.white


# --------------------------------------------------
# PAGE HEADER AND FOOTER
# --------------------------------------------------

def add_page_header_footer(canvas, document):

    canvas.saveState()

    page_width, page_height = A4

    canvas.setFont("Helvetica-Bold", 9)
    canvas.setFillColor(NAVY)

    canvas.drawString(
        20 * mm,
        page_height - 12 * mm,
        "GENOME SEQUENCE ANALYSIS TOOL"
    )

    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(MID_GREY)

    canvas.drawRightString(
        page_width - 20 * mm,
        page_height - 12 * mm,
        "DNA ANALYSIS REPORT"
    )

    canvas.setStrokeColor(LIGHT_BLUE)
    canvas.setLineWidth(0.8)

    canvas.line(
        20 * mm,
        page_height - 16 * mm,
        page_width - 20 * mm,
        page_height - 16 * mm
    )

    canvas.setStrokeColor(LIGHT_BLUE)

    canvas.line(
        20 * mm,
        15 * mm,
        page_width - 20 * mm,
        15 * mm
    )

    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(MID_GREY)

    canvas.drawString(
        20 * mm,
        10 * mm,
        "Generated by Genome Sequence Analysis Tool"
    )

    canvas.drawRightString(
        page_width - 20 * mm,
        10 * mm,
        f"Page {document.page}"
    )

    canvas.restoreState()


# --------------------------------------------------
# PDF REPORT GENERATOR
# --------------------------------------------------

def generate_pdf_report(
    sequence,
    length,
    composition,
    gc_content,
    at_content,
    reverse_complement,
    rna_sequence,
    protein_sequence,
    ambiguous_count=None,
    six_frame_translations=None,
    orfs=None,
    codon_statistics=None,
    gc_window_results=None,
    gc_statistics=None
):
    """
    Generate a professionally formatted DNA analysis PDF.

    Existing arguments remain compatible.

    Additional scientific sections are included
    when their corresponding data is supplied.

    Returns PDF data as bytes.
    """

    buffer = BytesIO()

    generation_time = datetime.now().strftime(
        "%d %B %Y | %I:%M %p"
    )

    document = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=20 * mm,
        leftMargin=20 * mm,
        topMargin=23 * mm,
        bottomMargin=22 * mm,
        title="DNA Sequence Analysis Report",
        author="Genome Sequence Analysis Tool",
        subject="DNA sequence analysis results"
    )

    # --------------------------------------------------
    # STYLES
    # --------------------------------------------------

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "ReportTitle",
        parent=styles["Title"],
        fontName="Helvetica-Bold",
        fontSize=21,
        leading=27,
        textColor=NAVY,
        alignment=0,
        spaceAfter=5
    )

    subtitle_style = ParagraphStyle(
        "ReportSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=11,
        leading=16,
        textColor=MID_GREY,
        spaceAfter=8
    )

    heading_style = ParagraphStyle(
        "SectionHeading",
        parent=styles["Heading2"],
        fontName="Helvetica-Bold",
        fontSize=12,
        leading=16,
        textColor=NAVY,
        spaceBefore=13,
        spaceAfter=7,
        keepWithNext=True
    )

    body_style = ParagraphStyle(
        "ReportBody",
        parent=styles["BodyText"],
        fontName="Helvetica",
        fontSize=9,
        leading=14,
        textColor=DARK_GREY,
        spaceAfter=5
    )

    sequence_style = ParagraphStyle(
        "SequenceText",
        parent=styles["Code"],
        fontName="Courier",
        fontSize=8,
        leading=13,
        textColor=NAVY,
        wordWrap="CJK",
        spaceAfter=4
    )

    metadata_style = ParagraphStyle(
        "Metadata",
        parent=styles["Normal"],
        fontSize=8,
        leading=12,
        textColor=MID_GREY
    )

    # --------------------------------------------------
    # TABLE STYLING
    # --------------------------------------------------

    def style_table(table):

        table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), NAVY),
            ("TEXTCOLOR", (0, 0), (-1, 0), WHITE),

            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTNAME", (0, 1), (-1, -1), "Helvetica"),

            ("FONTSIZE", (0, 0), (-1, -1), 9),

            ("BACKGROUND", (0, 1), (-1, -1), LIGHT_GREY),

            ("TEXTCOLOR", (0, 1), (-1, -1), DARK_GREY),

            ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#D9E0E7")),

            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),

            ("LEFTPADDING", (0, 0), (-1, -1), 9),
            ("RIGHTPADDING", (0, 0), (-1, -1), 9),

            ("TOPPADDING", (0, 0), (-1, -1), 8),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
        ]))

        return table

    # --------------------------------------------------
    # HELPER FUNCTIONS
    # --------------------------------------------------

    def add_sequence_block(story, value):

        value = str(value)

        lines = [
            value[i:i + 60]
            for i in range(0, len(value), 60)
        ]

        formatted = "<br/>".join(
            escape(line)
            for line in lines
        )

        story.append(
            Paragraph(
                formatted if formatted else "Not available",
                sequence_style
            )
        )

    def add_heading(story, title):

        story.append(
            Paragraph(title, heading_style)
        )

    def add_simple_table(story, data, widths):

        table = Table(
            data,
            colWidths=widths,
            repeatRows=1,
            splitByRow=1
        )

        story.append(style_table(table))

    # --------------------------------------------------
    # REPORT CONTENT
    # --------------------------------------------------

    story = []

    # TITLE

    story.append(
        Paragraph(
            "Genome Sequence<br/>Analysis Report",
            title_style
        )
    )

    story.append(
        Paragraph(
            "Computational analysis of DNA sequence data",
            subtitle_style
        )
    )

    story.append(
        Paragraph(
            f"Report generated: {generation_time}",
            metadata_style
        )
    )

    story.append(Spacer(1, 8))

    story.append(
        HRFlowable(
            width="100%",
            thickness=1.2,
            color=BLUE,
            spaceAfter=8
        )
    )

    # --------------------------------------------------
    # 1. ORIGINAL DNA SEQUENCE
    # --------------------------------------------------

    add_heading(story, "1. Original DNA Sequence")

    story.append(
        Paragraph(
            f"Sequence length: <b>{length} base pairs</b>",
            body_style
        )
    )

    sequence_lines = [
        sequence[i:i + 60]
        for i in range(0, len(sequence), 60)
    ]

    formatted_sequence = "<br/>".join(
        escape(line)
        for line in sequence_lines
    )

    sequence_table = Table(
        [[Paragraph(formatted_sequence, sequence_style)]],
        colWidths=[170 * mm]
    )

    sequence_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), LIGHT_BLUE),
        ("BOX", (0, 0), (-1, -1), 0.6, colors.HexColor("#C9DCEB")),
        ("LEFTPADDING", (0, 0), (-1, -1), 10),
        ("RIGHTPADDING", (0, 0), (-1, -1), 10),
        ("TOPPADDING", (0, 0), (-1, -1), 10),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 10),
    ]))

    story.append(sequence_table)

    # --------------------------------------------------
    # 2. SEQUENCE STATISTICS
    # --------------------------------------------------

    add_heading(story, "2. Sequence Statistics")

    statistics_data = [
        ["Parameter", "Result"],
        ["Sequence Length", f"{length} bp"],
        ["GC Content", f"{gc_content}%"],
        ["AT Content", f"{at_content}%"]
    ]

    if ambiguous_count is not None:

        statistics_data.append(
            ["Ambiguous Nucleotides", str(ambiguous_count)]
        )

        statistics_data.append(
            [
                "Canonical Nucleotides",
                str(length - ambiguous_count)
            ]
        )

    add_simple_table(
        story,
        statistics_data,
        [85 * mm, 85 * mm]
    )

    # --------------------------------------------------
    # 3. NUCLEOTIDE COMPOSITION
    # --------------------------------------------------

    add_heading(story, "3. Nucleotide Composition")

    composition_data = [
        ["Nucleotide", "Name", "Count"],
        ["A", "Adenine", composition["A"]],
        ["T", "Thymine", composition["T"]],
        ["G", "Guanine", composition["G"]],
        ["C", "Cytosine", composition["C"]]
    ]

    add_simple_table(
        story,
        composition_data,
        [35 * mm, 85 * mm, 50 * mm]
    )

    # --------------------------------------------------
    # 4. REVERSE COMPLEMENT
    # --------------------------------------------------

    add_heading(story, "4. Reverse Complement")

    story.append(
        Paragraph(
            "The reverse complement represents the complementary "
            "DNA strand written in the opposite direction.",
            body_style
        )
    )

    add_sequence_block(story, reverse_complement)

    # --------------------------------------------------
    # 5. DNA TRANSCRIPTION
    # --------------------------------------------------

    add_heading(story, "5. DNA Transcription")

    story.append(
        Paragraph(
            "Transcription converts the DNA sequence into "
            "a corresponding RNA sequence.",
            body_style
        )
    )

    add_sequence_block(story, rna_sequence)

    # --------------------------------------------------
    # 6. PROTEIN TRANSLATION
    # --------------------------------------------------

    add_heading(story, "6. Protein Translation")

    story.append(
        Paragraph(
            "Translation converts RNA codons into an amino acid "
            "sequence using the standard genetic code.",
            body_style
        )
    )

    add_sequence_block(story, protein_sequence)

    # --------------------------------------------------
    # 7. SIX-FRAME TRANSLATION
    # --------------------------------------------------

    if six_frame_translations is not None:

        add_heading(story, "7. Six-Frame Translation")

        story.append(
            Paragraph(
                "The DNA sequence is translated across three "
                "forward and three reverse reading frames.",
                body_style
            )
        )

        for frame, protein in six_frame_translations.items():

            story.append(
                Paragraph(
                    f"<b>Reading Frame {escape(str(frame))}</b>",
                    body_style
                )
            )

            add_sequence_block(story, protein)

    # --------------------------------------------------
    # 8. OPEN READING FRAME ANALYSIS
    # --------------------------------------------------

    if orfs is not None:

        add_heading(story, "8. Open Reading Frame Analysis")

        story.append(
            Paragraph(
                f"Total complete ORFs detected: <b>{len(orfs)}</b>",
                body_style
            )
        )

        if orfs:

            orf_data = [
                [
                    "Frame",
                    "Start",
                    "End",
                    "Length",
                    "Protein Length"
                ]
            ]

            for orf in orfs:

                orf_data.append([
                    escape(str(orf["frame"])),
                    str(orf["start_position"]),
                    str(orf["end_position"]),
                    f'{orf["length"]} bp',
                    str(orf["protein_length"])
                ])

            add_simple_table(
                story,
                orf_data,
                [25 * mm, 30 * mm, 30 * mm, 35 * mm, 50 * mm]
            )

            story.append(Spacer(1, 8))

            for index, orf in enumerate(orfs, start=1):

                story.append(
                    Paragraph(
                        f"<b>ORF {index} — {escape(str(orf['frame']))}</b>",
                        body_style
                    )
                )

                story.append(
                    Paragraph(
                        f"Start codon: {escape(str(orf['start_codon']))} | "
                        f"Stop codon: {escape(str(orf['stop_codon']))}",
                        metadata_style
                    )
                )

                add_sequence_block(
                    story,
                    orf["protein_sequence"]
                )

        else:

            story.append(
                Paragraph(
                    "No complete ORFs were detected.",
                    body_style
                )
            )

    # --------------------------------------------------
    # 9. CODON FREQUENCY ANALYSIS
    # --------------------------------------------------

    if codon_statistics is not None:

        add_heading(story, "9. Codon Frequency Analysis")

        story.append(
            Paragraph(
                f"Total possible codons: "
                f"<b>{codon_statistics['total_possible_codons']}</b>",
                body_style
            )
        )

        story.append(
            Paragraph(
                f"Valid codons: "
                f"<b>{codon_statistics['total_valid_codons']}</b>",
                body_style
            )
        )

        story.append(
            Paragraph(
                f"Excluded codons: "
                f"<b>{codon_statistics['excluded_codons']}</b>",
                body_style
            )
        )

        story.append(
            Paragraph(
                f"Start codons (ATG): "
                f"<b>{codon_statistics['start_codon_count']}</b>",
                body_style
            )
        )

        codon_data = [
            ["Codon", "Count", "Percentage"]
        ]

        percentages = codon_statistics["codon_percentages"]

        for codon, count in codon_statistics["codon_counts"].items():

            codon_data.append([
                codon,
                str(count),
                f"{percentages[codon]}%"
            ])

        if len(codon_data) > 1:

            add_simple_table(
                story,
                codon_data,
                [55 * mm, 55 * mm, 60 * mm]
            )

        else:

            story.append(
                Paragraph(
                    "No valid codons available.",
                    body_style
                )
            )

    # --------------------------------------------------
    # 10. SLIDING-WINDOW GC ANALYSIS
    # --------------------------------------------------

    if gc_window_results is not None:

        add_heading(story, "10. Sliding-Window GC Analysis")

        if gc_statistics is not None:

            gc_summary = [
                ["Parameter", "Result"],
                [
                    "Total Windows",
                    str(gc_statistics["total_windows"])
                ],
                [
                    "Average GC Content",
                    f'{gc_statistics["average_gc"]}%'
                ],
                [
                    "Maximum GC Content",
                    f'{gc_statistics["maximum_gc"]}%'
                ],
                [
                    "Minimum GC Content",
                    f'{gc_statistics["minimum_gc"]}%'
                ]
            ]

            add_simple_table(
                story,
                gc_summary,
                [85 * mm, 85 * mm]
            )

        if gc_window_results:

            story.append(Spacer(1, 8))

            window_data = [
                [
                    "Start",
                    "End",
                    "GC Content",
                    "Valid Bases"
                ]
            ]

            for window in gc_window_results[:50]:

                window_data.append([
                    str(window["start_position"]),
                    str(window["end_position"]),
                    f'{window["gc_content"]}%',
                    str(window["valid_bases"])
                ])

            add_simple_table(
                story,
                window_data,
                [35 * mm, 35 * mm, 50 * mm, 50 * mm]
            )

            if len(gc_window_results) > 50:

                story.append(
                    Paragraph(
                        "Note: The table displays the first 50 windows. "
                        "The complete results are available in the application.",
                        metadata_style
                    )
                )

        else:

            story.append(
                Paragraph(
                    "No GC window results available.",
                    body_style
                )
            )

    # --------------------------------------------------
    # FINAL NOTE
    # --------------------------------------------------

    story.append(Spacer(1, 18))

    story.append(
        HRFlowable(
            width="100%",
            thickness=0.6,
            color=LIGHT_BLUE,
            spaceAfter=8
        )
    )

    story.append(
        Paragraph(
            "<b>Report Information</b>",
            body_style
        )
    )

    story.append(
        Paragraph(
            "This report contains computational results generated "
            "from the submitted DNA sequence. Results should be "
            "interpreted in the context of the biological question "
            "and the limitations of the analysis methods.",
            metadata_style
        )
    )

    # --------------------------------------------------
    # BUILD PDF
    # --------------------------------------------------

    document.build(
        story,
        onFirstPage=add_page_header_footer,
        onLaterPages=add_page_header_footer
    )

    pdf_data = buffer.getvalue()

    buffer.close()

    return pdf_data